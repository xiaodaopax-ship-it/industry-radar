def _pct(vals, q):
    s = sorted(vals)
    if not s:
        return None
    k = (len(s) - 1) * q / 100
    lo, hi = int(k), min(int(k) + 1, len(s) - 1)
    return s[lo] + (s[hi] - s[lo]) * (k - lo)


def _series(hist, today):
    """Down-sampled PE(TTM) history, percentile band, and ~1 year of daily close (unadjusted) from valuation_history."""
    pe = [(h["date"], h["pe_ttm"]) for h in hist if h.get("date") and h.get("pe_ttm") is not None]
    step = max(1, len(pe) // CARD_RULES["pe_points"])
    pe_s = pe[::step]
    if pe and pe_s[-1] != pe[-1]:
        pe_s.append(pe[-1])
    pos = [v for _, v in pe if v > 0]
    band = {"p20": _pct(pos, 20), "p50": _pct(pos, 50), "p80": _pct(pos, 80), "n": len(pos)} if pos else None
    start = (today - dt.timedelta(days=CARD_RULES["price_days"])).isoformat()
    px = [(h["date"], h["close"]) for h in hist if h.get("date") and h["date"] >= start and h.get("close") is not None]
    return ([[d, round(v, 2)] for d, v in pe_s], band, [[d, round(v, 3)] for d, v in px])


def latest_snap():
    files = sorted(glob.glob(os.path.join(DATA_DIR, "snap_*.json")))
    return files[-1] if files else None


def latest_cards():
    files = sorted(glob.glob(os.path.join(DATA_DIR, "cards_*.json")))
    return files[-1] if files else None


def fetch_cards(snap_path=None, snap=None):
    """Fetch per-stock extras for the card stocks of a snapshot and save data/cn/cards_<ts>.json."""
    from .build import analyze, RULES  # local import: build imports this module
    if snap is None:
        snap_path = snap_path or latest_snap()
        if not snap_path:
            log("ERROR: no data/cn/snap_*.json found; run `python -m cn fetch` first")
            return None
        with open(snap_path, encoding="utf-8") as f:
            snap = json.load(f)
    res = analyze(snap)
    codes = card_codes(res)
    today = dt.date.today()
    t0 = dt.datetime.now(em.CST)
    P = snap["periods"]
    # reuse fields already fetched for the same snapshot (only missing / failed fields are fetched again)
    prev_doc, prev_path = {}, latest_cards()
    if prev_path and snap_path:
        try:
            with open(prev_path, encoding="utf-8") as f:
                d = json.load(f)
            if d.get("snap") == os.path.basename(snap_path):
                prev_doc = d.get("cards") or {}
        except (OSError, ValueError):
            prev_doc = {}
    log(f"cards: {len(codes)} stocks (priority {len(res['priority'])} + value label, deduplicated) from {os.path.basename(snap_path or '')}"
        + (f"; reusing fields from {os.path.basename(prev_path)}" if prev_doc else ""))
    out, failed, reused = {}, {}, 0
    for i, code in enumerate(codes, 1):
        rec, errs = {}, []
        old = prev_doc.get(code) or {}
        old_err = set(old.get("errors") or [])

        def have(field, *keys):
            return bool(old) and field not in old_err and all(k in old for k in keys)

        def call(field, fn, *a):
            before = em.STATS["failures"]
            v = fn(*a)
            if em.STATS["failures"] > before:
                errs.append(field)
            return v

        if have("profile", "profile"):
            rec["profile"] = old["profile"]; reused += 1
        else:
            prof = call("profile", em.company_profile, code)
            rec["profile"] = prof[0] if prof else None
        if have("mainop", "mainop"):
            rec["mainop"] = old["mainop"]; reused += 1
        else:
            rec["mainop"] = call("mainop", em.main_business_composition, code)
        if have("float_holders", "float_holders"):
            rec["float_holders"] = old["float_holders"]; reused += 1
        else:
            rec["float_holders"] = call("float_holders", em.float_holders, code)
        if have("consensus", "consensus"):
            rec["consensus"] = old["consensus"]; reused += 1
        else:
            ac = call("consensus", em.analyst_consensus, code)
            rec["consensus"] = ac[0] if ac else None
        if have("valuation_history", "pe_series", "pe_band", "price", "hist_range"):
            for k in ("pe_series", "pe_band", "price", "hist_range"):
                rec[k] = old[k]
            reused += 1
        else:
            hist = call("valuation_history", em.valuation_history, code, RULES["valuation_years"])
            rec["pe_series"], rec["pe_band"], rec["price"] = _series(hist, today)
            rec["hist_range"] = [hist[0]["date"], hist[-1]["date"]] if hist else None
        # 扣非 EPS / profit for the latest YTD period and the same period last year (historical PEG fallback)
        if have("deducted", "deducted") and all(p in (old["deducted"] or {}) for p in (P["latest"], P["year_ago"])):
            rec["deducted"] = old["deducted"]; reused += 1
        else:
            dh = call("deducted", em.deducted_history, code, P["year_ago"], P["latest"])
            rec["deducted"] = {k: v for k, v in dh.items() if k in (P["latest"], P["year_ago"])}
        rec["errors"] = errs
        for e in errs:
            failed[e] = failed.get(e, 0) + 1
        out[code] = rec
        if i % 10 == 0:
            log(f"  cards {i}/{len(codes)}")
    doc = {"fetched_at": t0.strftime("%Y-%m-%d %H:%M"), "snap": os.path.basename(snap_path) if snap_path else None,
           "snap_fetched_at": snap.get("fetched_at"), "codes": codes, "rules": CARD_RULES, "cards": out,
           "failed_fields": failed, "http": dict(em.STATS)}
    os.makedirs(DATA_DIR, exist_ok=True)
    path = os.path.join(DATA_DIR, f"cards_{t0.strftime('%Y%m%d_%H%M%S')}.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False)
    n = {k: sum(1 for c in out.values() if c.get(k)) for k in ("profile", "mainop", "float_holders", "consensus", "price", "deducted")}
    log(f"saved {os.path.relpath(path, ROOT)} ({os.path.getsize(path) / 1e6:.2f} MB); with_data={n}; reused_fields={reused}; "
        f"failed={failed}; http={em.STATS}")
    return path


# ----------------------------------------------------------------------------- rules -> card content
def _f(v, d=1):
    return "—" if v is None else f"{v:.{d}f}"


def _s(v, d=0):
    return "—" if v is None else f"{v:+.{d}f}"


def _yi(v):
    return "—" if v is None else f"{v / 1e8:.1f}"


def _oneliner(prof):
    t = (prof or {}).get("main_business") or (prof or {}).get("profile") or ""
    t = re.split(r"[。；;]", t.strip())[0].strip()
    return (t[:60] + "…") if len(t) > 60 else t


def _research(code):
    p = os.path.join(RESEARCH_DIR, f"{code}.json")
    if not os.path.exists(p):
        return None
    try:
        with open(p, encoding="utf-8") as f:
            d = json.load(f)
        if not isinstance(d, dict) or str(d.get("code", code)) != code:
            log(f"WARNING: {os.path.relpath(p, ROOT)} ignored (code mismatch or not an object)")
            return None
        return d
    except (OSError, ValueError) as e:
        log(f"WARNING: {os.path.relpath(p, ROOT)} unreadable ({type(e).__name__})")
        return None


PEG_CYC_REASON = "周期行业，盈利高点时 PE 最低，PEG 不适用"
PEG_HIST_CN = "历史口径（扣非，年初至今同比）"


def peg(r, x, P):
    """PEG for one card stock. Forward (consensus EPS CAGR from the current-year estimate) when the consensus is
    usable, otherwise historical (扣非 YTD YoY). Returns a dict; value None => not shown, see 'reason'.
    flags non-empty => shown but unreliable (status na). Reference only: never used in ranking / labels / warn_n."""
    C = CARD_RULES
    o = {"value": None, "method": None, "growth": None, "status": "na", "flags": [], "reason": None, "short": None,
         "line": None, "fwd_note": None}
    pe = r.get("pe_ttm")
    if r.get("cyclical"):
        o["reason"] = PEG_CYC_REASON
        return o
    if pe is None or pe <= 0:
        o["reason"] = "PE(TTM) ≤ 0 或缺失，PEG 不适用"
        return o

    def finish(g, short, line):
        o["growth"], o["short"] = round(g, 1), short
        o["brief"] = short.strip() + (" 年化 " if o["method"] == "forward" else " ") + f"{g:+.0f}%"
        if g > C["peg_growth_max"]:
            o["flags"].append(f"增速 {g:+.0f}% > {C['peg_growth_max']:.0f}%，PEG 不可靠")
        if g <= 0:
            o["reason"] = f"{short}增速 {g:+.0f}% ≤ 0，PEG 不适用"
            return o
        v = pe / g
        o["value"] = round(v, 2)
        o["line"] = f"PEG {v:.2f}（{line}）"
        o["status"] = "na" if o["flags"] else ("ok" if v <= C["peg_ok_max"] else "warn" if v > C["peg_warn_min"] else "na")
        return o

    # ---- forward: consensus mean EPS, current-year estimate -> two years later
    a = x.get("consensus")
    y_rep = int(P["latest"][:4])
    est = {e["year"]: e["eps"] for e in (a or {}).get("eps", []) if e.get("kind") == "estimate" and e.get("eps") is not None}
    act = {e["year"]: e["eps"] for e in (a or {}).get("eps", []) if e.get("kind") == "actual" and e.get("eps") is not None}
    y0 = min((y for y in est if y >= y_rep), default=None)
    why = None
    if not a:
        why = "无机构一致预期"
    elif (a.get("org_num") or 0) < C["peg_min_org"]:
        why = f"一致预期覆盖机构 {a.get('org_num') or 0:.0f} 家 < {C['peg_min_org']}"
    elif y0 is None:
        why = f"缺当年（{y_rep}E）一致预期"
    else:
        n = 2 if (y0 + 2) in est and (y0 + 1) in est else 1 if (y0 + 1) in est else 0
        path = [est[y0 + k] for k in range(n + 1)]
        if n == 0:
            why = f"只有 {y0}E 一年预期，无法计算增速"
        elif any(e <= 0 for e in path):
            why = "一致预期 EPS 有 ≤ 0 的年度"
    if why is None:
        yn, e0, en = y0 + n, path[0], path[-1]
        g = ((en / e0) ** (1 / n) - 1) * 100
        o["method"] = "forward"
        o["years"], o["org_num"], o["eps_path"] = [y0, yn], a.get("org_num"), [round(e, 3) for e in path]
        if e0 < C["peg_fwd_eps_min"]:
            o["flags"].append(f"基数低：{y0}E EPS {e0:.2f} < {C['peg_fwd_eps_min']} 元，PEG 不可靠")
        la = act.get(y0 - 1)
        if la is not None and la <= C["peg_fwd_actual_ratio"] * e0:
            o["flags"].append(f"基数低：{y0 - 1}A EPS {la:.2f} → {y0}E {e0:.2f}，PE(TTM) 主要反映低基数期盈利，PEG 不可靠")
        drops = [(y0 + k, path[k], path[k + 1]) for k in range(n) if path[k + 1] < path[k] * (1 - C["peg_fwd_drop_pct"] / 100)]
        if drops:
            y, p0, p1 = drops[0]
            o["flags"].append(f"一致预期年度间大幅下降（{y}E {p0:.2f} → {y + 1}E {p1:.2f}），可能含一次性收益")
        one = "，只有两年预期，按 1 年增速" if n == 1 else ""
        return finish(g, f"前瞻 {y0}E→{yn}E ", f"前瞻，{y0}E→{yn}E 年化 {g:+.0f}%，{a.get('org_num') or 0:.0f} 家机构{one}")

    # ---- historical: 扣非, latest YTD vs same YTD period last year
    o["fwd_note"] = why
    ded = x.get("deducted") or {}
    cur, old = ded.get(P["latest"]) or {}, ded.get(P["year_ago"]) or {}
    pc, po = cur.get("deducted_net_profit"), old.get("deducted_net_profit")
    ec, eo = cur.get("eps_deducted"), old.get("eps_deducted")
    if ec is not None and eo is not None and ec >= C["peg_hist_eps_min"] and eo >= C["peg_hist_eps_min"]:
        basis, vc, vo = "扣非 EPS", ec, eo
    elif pc is not None and po is not None:
        basis, vc, vo = "扣非归母净利润", pc, po
    elif ec is not None and eo is not None:
        basis, vc, vo = "扣非 EPS", ec, eo
    else:
        o["reason"] = f"{why}；也没有取到 {P['latest']} / {P['year_ago']} 扣非数据，PEG 不适用"
        return o
    o["method"], o["basis"] = "historical", basis
    o["hist"] = {"cur": vc, "old": vo, "cur_np": pc, "old_np": po}
    if vo <= 0:
        o["reason"] = f"{why}；上年同期（{P['year_ago']}）{basis} ≤ 0，增速不可计算，PEG 不适用"
        return o
    g = (vc / vo - 1) * 100
    if po is not None and pc is not None and (po < C["peg_hist_base_ratio"] * pc or po < C["peg_hist_base_min"]):
        o["flags"].append(f"基数低：上年同期扣非归母净利润 {po / 1e4:,.0f} 万元（本期 {pc / 1e4:,.0f} 万元），PEG 不可靠")
    elif po is None and vo < C["peg_hist_base_ratio"] * vc:
        o["flags"].append("基数低，PEG 不可靠")
    return finish(g, f"{PEG_HIST_CN} ",
                  f"{PEG_HIST_CN}，{P['latest']} vs {P['year_ago']} {basis} {g:+.0f}%；{why}")


def card_payload(snap, res, cards_doc, rules):
    """List of card dicts (priority order, then 偏价值) for the template. cards_doc may be None (snapshot-only cards)."""
    P = snap["periods"]
    today = dt.date.fromisoformat(snap["today"])
    by = {r["code"]: r for r in res["screen"]}
    prio = {p["code"]: p for p in res["priority"]}
    extra = (cards_doc or {}).get("cards", {})
    hold, unl, fc, reg = {}, {}, {}, {}
    seen = set()
    for h in snap["holders"]:
        key = (h["source"], h["code"], h.get("holder"), h.get("start_date"), h.get("date"), h.get("shares"))
        if key in seen or h.get("shares") is None:
            continue
        seen.add(key)
        hold.setdefault(h["code"], []).append(h)
    for u in snap["unlocks"]:
        unl.setdefault(u["code"], []).append(u)
    for r in snap["forecasts"]:
        fc.setdefault(r["code"], []).append(r)
    for r in snap["regulatory"]:
        if r.get("kind") in REG_COUNT_KINDS:
            reg.setdefault(r["code"], []).append(r)
    quote = {q["code"]: q for q in snap["quotes"]}
    out = []
    for code in card_codes(res):
        r, p, x = by[code], prio.get(code), extra.get(code) or {}
        g = r["gates"]
        prof = x.get("profile")
        mo = x.get("mainop") or []
        prod = sorted([m for m in mo if m["type"] == "product"], key=lambda m: -(m["revenue"] or 0))
        regn = sorted([m for m in mo if m["type"] == "region"], key=lambda m: -(m["revenue"] or 0))
        if not prod:
            prod = sorted([m for m in mo if m["type"] == "industry"], key=lambda m: -(m["revenue"] or 0))
        fh = x.get("float_holders") or []
        h_rows = sorted(hold.get(code, []), key=lambda h: h.get("date") or "", reverse=True)
        u_rows = sorted(unl.get(code, []), key=lambda u: u.get("date") or "")
        f_rows = sorted(fc.get(code, []), key=lambda f: f.get("notice_date") or "", reverse=True)[:3]
        reg_rows = sorted(reg.get(code, []), key=lambda f: f.get("date") or "", reverse=True)[:10]
        val = (snap.get("valuation") or {}).get(code) or {}
        pe, pb = val.get("pe") or {}, val.get("pb") or {}
        q = quote.get(code, {})
        ts = q.get("total_shares")

        # ---- tiles
        acc = r["accel"]
        t_growth = {"label": "增长（年初至今营收同比）", "main": f"{_s(r['rev_yoy'])}%",
                    "sub": (f"上期累计 {_s(r['rev_yoy_prev'])}%，{'加速' if acc >= 0 else '放缓'} {abs(acc):.0f}pp" if acc is not None else "无上期同比")
                    + f"；净利同比 {_s(r['np_yoy'])}%",
                    "s": "warn" if (acc is not None and acc <= CARD_RULES["accel_slow_pp"]) or (r["np_yoy"] is not None and r["np_yoy"] < 0) else "ok"}
        cash_s = [g[k]["s"] for k in ("ocf", "ar", "inv")]
        t_cash = {"label": "现金流质量（经营现金流 / 归母净利润）", "main": _f(r["ocf_np"], 2),
                  "sub": f"应收 {g['ar']['sv']} · 存货 {g['inv']['sv']}（营收 {_s(r['rev_yoy'])}%）",
                  "s": "warn" if "warn" in cash_s else ("ok" if g["ocf"]["s"] == "ok" else "na")}
        t_val = {"label": "估值（近 5 年分位）", "main": f"PE 分位 {_f(r['pe_pct'], 0)}%" if r["pe_pct"] is not None else "PE 分位 —",
                 "sub": f"PE(TTM) {_f(r['pe_ttm'])} · PB {_f(r['pb'], 2)}（分位 {_f(r['pb_pct'], 0)}%）", "s": g["val"]["s"]}
        pg = peg(r, x, P)
        t_val["sub2"] = (pg["line"] + ("；⚠ " + "；".join(pg["flags"]) if pg["flags"] else "")) if pg["value"] is not None \
            else "PEG —（" + pg["reason"] + ("；" + "；".join(pg["flags"]) if pg["flags"] else "") + "）"
        t_val["sub2_s"] = pg["status"]
        ev_keys = ("pledge", "selling", "unlock", "reg")
        ev_warn = sum(1 for k in ev_keys if g[k]["s"] == "warn")
        t_event = {"label": "事件风险（质押 / 减持 / 解禁 / 监管）", "main": f"{ev_warn} 项提示",
                   "sub": f"质押 {g['pledge']['sv']} · 净增减持 {g['selling']['sv']} · 解禁 {g['unlock']['sv']} · 监管 {g['reg']['sv']}",
                   "s": "warn" if ev_warn else "ok"}

        # ---- opportunities / risks (each cites its number)
        bull, bear = [], []
        bull.append(f"{P['latest']} 年初至今营收 {_yi(r['revenue'])} 亿元，同比 {_s(r['rev_yoy'])}%")
        if acc is not None and acc > 0:
            bull.append(f"增速比 {P['prev']} 累计口径提高 {acc:.0f}pp（{_s(r['rev_yoy_prev'])}% → {_s(r['rev_yoy'])}%）")
        if r["ocf_np"] is not None and r["ocf_np"] >= CARD_RULES["ocf_strong"]:
            bull.append(f"经营现金流 / 归母净利润 {r['ocf_np']:.2f}，利润有经营现金流对应")
        if r["np_yoy"] is not None and r["rev_yoy"] is not None and r["np_yoy"] > r["rev_yoy"] > 0:
            bull.append(f"归母净利润同比 {_s(r['np_yoy'])}%，快于营收")
        if r["gm_chg"] is not None and r["gm_chg"] >= CARD_RULES["gm_rise_pp"]:
            bull.append(f"毛利率 {_f(r['gm'])}%，同比 {_s(r['gm_chg'], 1)}pp")
        if r["pe_pct"] is not None and r["pe_pct"] <= CARD_RULES["pe_low_pct"]:
            bull.append(f"PE(TTM) {_f(r['pe_ttm'])} 位于近 5 年 {r['pe_pct']:.0f}% 分位（只是相对自身历史的位置）")
        if f_rows and g["fc"]["s"] == "ok":
            bull.append(f"最新业绩预告：{g['fc']['v']}（{f_rows[0].get('notice_date')} 公告）")
        hn = [h for h in h_rows if h.get("shares")]
        net = sum(h["shares"] for h in hn) if hn else None
        if net is not None and ts and net > 0:
            bull.append(f"近 {rules['holder_months']} 个月董监高与股东净增持 {100 * net / ts:.2f}% 总股本")
        new_h = [h for h in fh if h["status"] == "new"]
        if new_h:
            bull.append(f"{fh[0]['end_date']} 前十大流通股东新进 {len(new_h)} 家（{('、'.join(h['holder'] for h in new_h[:2]))[:40]}{'等' if len(new_h) > 2 else ''}）")
        for k in ("ocf", "ar", "inv", "goodwill", "pledge", "selling", "unlock", "reg", "val", "fc"):
            if g[k]["s"] == "warn":
                bear.append({"ocf": "现金流/净利 ", "ar": "应收增速：", "inv": "存货增速：", "goodwill": "商誉/归母权益 ",
                             "pledge": "质押比例 ", "selling": "近 6 个月", "unlock": "90 天内解禁 ", "reg": "12 个月监管类标题 ",
                             "val": "估值位置：", "fc": "业绩预告："}[k] + g[k]["v"])
        if acc is not None and acc <= CARD_RULES["accel_slow_pp"]:
            bear.append(f"增速比上期累计口径放缓 {abs(acc):.0f}pp（{_s(r['rev_yoy_prev'])}% → {_s(r['rev_yoy'])}%）")
        if r["np_yoy"] is not None and r["np_yoy"] < 0:
            bear.append(f"归母净利润同比 {_s(r['np_yoy'])}%，营收增长没有转化为利润增长")
        if r["gm_chg"] is not None and r["gm_chg"] <= CARD_RULES["gm_drop_pp"]:
            bear.append(f"毛利率 {_f(r['gm'])}%，同比 {_s(r['gm_chg'], 1)}pp")
        if r["gm"] is not None and r["gm"] < CARD_RULES["low_gm"]:
            bear.append(f"毛利率 {_f(r['gm'])}%，低于 {CARD_RULES['low_gm']:.0f}%")
        top = prod[0] if prod else None
        if top and top.get("share_pct") is not None and top["share_pct"] >= CARD_RULES["top_item_share"]:
            bear.append(f"收入集中：{top['item']} 占主营收入 {top['share_pct']:.0f}%（{top['report_name'] or top['report_date']}）")
        dec_h = [h for h in fh if h["status"] in ("decrease", "exited")]
        if len(dec_h) >= 3:
            bear.append(f"{fh[0]['end_date']} 前十大流通股东中 {sum(1 for h in fh if h['status'] == 'decrease')} 家减持、"
                        f"{sum(1 for h in fh if h['status'] == 'exited')} 家退出")
        # ---- conclusion (data-level summary + top reasons, like radar/score.py conclusion())
        head = (f"研究优先级第 {p['rank']} 名（综合分 {_f(p['score'])}），" if p else "") + f"标签「{r['label']}」"
        b = "；".join(bull[:2]) or "数据上没有突出的优点"
        w = "；".join(bear[:2]) or "前 8 项风险门槛没有触发提示"
        concl = f"{head}。数据上的依据：{b}。需要注意：{w}。以上是按固定规则从公开数据生成的摘要，需要人工核实。"
        # PEG lines are appended after the conclusion is built (reference item, not part of the summary)
        if pg["value"] is not None and not pg["flags"]:
            basis = "只按一致预期计算" if pg["method"] == "forward" else "只按历史增速计算"
            if pg["status"] == "ok":
                bull.append(f"PEG {pg['value']:.2f}（{pg['brief']}）≤ {CARD_RULES['peg_ok_max']:g}，增速相对估值不贵（{basis}）")
            elif pg["status"] == "warn":
                bear.append(f"PEG {pg['value']:.2f}（{pg['brief']}）> {CARD_RULES['peg_warn_min']:g}（{basis}）")

        # ---- questions to verify (3..5)
        qs = []
        if pg["flags"]:
            qs.append(f"PEG 不可靠的原因：{'；'.join(pg['flags'])}——核对上年基数与一次性收益，看扣非净利润")
        if g["ocf"]["s"] == "warn" or g["ar"]["s"] == "warn":
            qs.append(f"应收增长的客户结构是什么：新增应收集中在哪些客户、账期有没有拉长（现金流/净利 {_f(r['ocf_np'], 2)}，应收 {g['ar']['sv']}）")
        if g["inv"]["s"] == "warn":
            qs.append(f"存货增长（{g['inv']['sv']}）是为订单备货还是周转变慢：看存货构成与跌价准备")
        if u_rows:
            u0 = u_rows[0]
            qs.append(f"解禁股东的减持计划：{u0.get('date')} 起 {u0.get('type_cn') or '限售股'} 解禁（合计 {g['unlock']['sv']} 流通股），留意减持预披露公告")
        if r["gm_chg"] is not None and r["gm_chg"] >= CARD_RULES["gm_jump_pp"]:
            qs.append(f"毛利率同比 {_s(r['gm_chg'], 1)}pp：是涨价、产品结构变化，还是一次性因素")
        if g["selling"]["s"] == "warn":
            qs.append("减持主体与原因：是否为已预披露的计划内减持，减持后持股比例")
        if reg_rows:
            qs.append(f"{len(reg_rows)} 条监管类公告标题的具体事项与公司回复（需阅读原文）")
        if r["np_yoy"] is not None and r["rev_yoy"] is not None and r["np_yoy"] - r["rev_yoy"] > CARD_RULES["np_rev_gap_pp"]:
            qs.append(f"净利同比 {_s(r['np_yoy'])}% 远高于营收同比 {_s(r['rev_yoy'])}%：有没有非经常性损益（对比扣非净利润）")
        if acc is not None and acc <= CARD_RULES["accel_slow_pp"]:
            qs.append("增速放缓：是上年基数原因还是需求变化")
        if r["pe_pct"] is not None and r["pe_pct"] >= rules["pe_pct_high"]:
            qs.append(f"PE 分位 {r['pe_pct']:.0f}%：当前估值隐含的增速假设，与订单 / 产能是否匹配")
        if top and top.get("share_pct") is not None and top["share_pct"] >= CARD_RULES["top_item_share"]:
            qs.append(f"{top['item']} 占比 {top['share_pct']:.0f}%：下游客户分布与订单可见度")
        qs += ["客户集中度：前五名客户销售额占比（年报披露）", "主营业务的竞争格局：主要对手与份额变化",
               "营收增长中量与价各贡献多少"]
        qs = list(dict.fromkeys(qs))[:5]

        # ---- evidence
        res_file = _research(code)
        out.append({
            "code": code, "name": r["name"], "industry": r["industry"], "board": r["board"], "label": r["label"],
            "reasons": r["reasons"], "rank": p["rank"] if p else None, "score": p["score"] if p else None,
            "factors": p["f"] if p else None, "val_basis": p["val_basis"] if p else None,
            "oneliner": _oneliner(prof), "conclusion": concl,
            "tiles": [t_growth, t_cash, t_val, t_event], "bull": bull, "bear": bear, "questions": qs,
            "gates": g, "warn_n": r["warn_n"], "peg": pg,
            "fin": {k: r[k] for k in ("revenue", "rev_yoy", "rev_yoy_prev", "accel", "np", "np_yoy", "gm", "gm_chg",
                                      "ocf_np", "mcap", "pe_ttm", "pb", "pe_pct", "pb_pct")} | {"price": q.get("price")},
            "valuation": {"pe": pe, "pb": pb, "first": val.get("first"), "last": val.get("last")},
            "pe_series": x.get("pe_series") or [], "pe_band": x.get("pe_band"), "price": x.get("price") or [],
            "mainop_product": prod[:5], "mainop_region": regn[:5],
            "float_holders": fh,
            "consensus": x.get("consensus"),
            "forecasts": [{k: f.get(k) for k in ("notice_date", "report_period", "forecast_type_cn", "forecast_type",
                                                 "yoy_low_pct", "yoy_high_pct", "profit_low", "profit_high")} for f in f_rows],
            "holders": [{"date": h.get("date"), "src": "董监高" if h["source"] == "executive" else "股东",
                         "holder": h.get("holder"), "shares": h.get("shares"), "ratio_pct": h.get("ratio_pct")}
                        for h in h_rows[:CARD_RULES["holder_rows"]]],
            "holders_n": len(h_rows), "holders_net_pct": (100 * net / ts) if (net is not None and ts) else None,
            "unlocks": [{k: u.get(k) for k in ("date", "shares", "tradable_shares", "ratio_float_pct", "unlock_value", "type_cn")}
                        for u in u_rows],
            "reg": [{"date": x2.get("date"), "kind": REG_KIND_CN.get(x2.get("kind"), x2.get("kind")), "title": x2.get("title_cn"),
                     "url": x2.get("url")} for x2 in reg_rows],
            "profile": {k: ((prof or {}).get(k) or "")[:600] if k == "profile" else (prof or {}).get(k) for k in ("org_name", "main_business", "profile", "industry_em", "industry_csrc",
                                                          "listing_date", "employees", "chairman", "president", "actual_holder",
                                                          "province", "website")} if prof else None,
            "research": res_file,
            "extra_ok": bool(x), "errors": x.get("errors") or [],
            "hist_range": x.get("hist_range"),
        })
    return out
